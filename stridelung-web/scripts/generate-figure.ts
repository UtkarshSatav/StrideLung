// Generates the StrideLung 01 figure data from the per-component geometry files.
//
//   npm run figure        full depth settle over every replayed frame of the explode (~6 min)
//   npm run figure:fast   quick settle for iteration (~15 s)
//   npm run figure:audit  full settle + the geometry audit (clearances, supports, depth order, …)
//
// Output: src/trolley/generated/scene.json (camera, back layer, doors, per-component bounds)
//         src/trolley/generated/parts/Cxx.json (that component's depth-sorted items)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { A, P, R, W, H, VIEW, KS, k, scene, PIECES, EXPLODE, ORDER, SPRING } from "../src/trolley/geometry/builder.ts";
import { buildPlinth } from "../src/trolley/geometry/scene/plinth.ts";
import { PARTS } from "../src/trolley/geometry/parts/index.ts";
import { REGISTER, MASS, RESOURCES, SUBSYSTEMS } from "../src/trolley/register.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "src", "trolley", "generated");
const FAST = process.argv.includes("--fast");
const AUDIT = process.argv.includes("--audit");

const t0 = Date.now();
buildPlinth();
for (const part of PARTS) part.build();

// Painter's order: measure true depth wherever two items overlap, at rest, apart and through the explode.
const states = FAST
  ? [...A.uniformStates(4), ...A.prefixStates(ORDER, { shares: [0.5, 1] })]
  : A.explodeStates(R.order, R.spring).depth;
A.settle(R, P, { states });
R.items.sort((a: any, b: any) => a.key - b.key);
const settle = ((Date.now() - t0) / 1000).toFixed(1);

const f2 = (v: number) => Math.round(v * 100) / 100;
const byPart: Record<string, any[]> = Object.fromEntries(REGISTER.map((row) => [row.id, []]));
const boxes: Record<string, number[] | null> = Object.fromEntries(REGISTER.map((row) => [row.id, null]));
const grow = (id: string, b: number[] | null) => {
  if (!b) return;
  const a = boxes[id];
  boxes[id] = a ? [Math.min(a[0], b[0]), Math.min(a[1], b[1]), Math.max(a[2], b[2]), Math.max(a[3], b[3])] : b;
};
R.items.forEach((item: any, index: number) => {
  byPart[item.c].push({
    i: index, // global painter's index after settling
    n: item.name,
    c: item.c,
    s: item.sys,
    x: item.also || undefined,
    p: item.piece,
    r: item.ride !== item.piece ? item.ride : undefined,
    k: f2(item.key),
    m: item.move.map(f2),
    a: item.attrs || undefined,
    t: item.title || undefined,
    svg: item.svg,
  });
  // the external-gas hose is only shown in that view, so it does not size its component's crop
  const b = item.name.startsWith("ext.") ? null : A.markupBox(item.svg);
  grow(item.c, b);
  for (const id of (item.also || "").split(" ").filter(Boolean)) grow(id, b);
});

const unitScreen = (v: number[]) => {
  const o = k.iso([0, 0, 0], P);
  const p = k.iso(v, P);
  return [f2(p[0] - o[0]), f2(p[1] - o[1])];
};
const sceneJson = {
  W, H, P, V: VIEW, KS,
  EX: unitScreen([1, 0, 0]), EY: unitScreen([0, 1, 0]), EZ: unitScreen([0, 0, 1]),
  back: scene.back.join(""),
  gasHatch: scene.gasHatch,
  handleClip: scene.handleClip,
  hinge: scene.hinge,
  doors: scene.doors,
  display: scene.display,
  pieces: Object.fromEntries(Object.entries(PIECES).map(([id, p]) => [id, { label: p.label }])),
  explode: EXPLODE,
  spring: SPRING,
  lines: Object.fromEntries(scene.lines.map((l) => [l.name, Math.round(l.length)])),
  c23: scene.c23,
  bounds: boxes,
  mass: MASS,
  resources: RESOURCES,
  subsystems: SUBSYSTEMS,
  itemCount: R.items.length,
};
mkdirSync(join(OUT, "parts"), { recursive: true });
writeFileSync(join(OUT, "scene.json"), JSON.stringify(sceneJson));
for (const [id, items] of Object.entries(byPart)) writeFileSync(join(OUT, "parts", `${id}.json`), JSON.stringify(items));
// a typed index so the app can import every component's items statically
const index = `// Generated by scripts/generate-figure.ts — do not edit.\n` +
  REGISTER.map((row) => `import ${row.id} from "./parts/${row.id}.json";`).join("\n") +
  `\nimport sceneData from "./scene.json";\nimport type { SceneData, Item } from "../types";\n\nexport const scene = sceneData as unknown as SceneData;\nexport const partItems: Record<string, Item[]> = { ${REGISTER.map((row) => `${row.id}: ${row.id} as unknown as Item[]`).join(", ")} };\n`;
writeFileSync(join(OUT, "index.ts"), index);

const kb = Math.round(Object.values(byPart).reduce((a, list) => a + JSON.stringify(list).length, 0) / 1024);
console.log(`figure: ${R.items.length} items · ${R.solids.length} solids · ${R.tubes.length} tube runs · ${kb} KB of item markup · settle ${settle}s${FAST ? " (fast)" : ""}`);
console.log(`lines: ${scene.lines.map((l) => `${l.name} ${Math.round(l.length)}mm`).join(" · ")}`);

if (AUDIT) {
  // A trimmed frame set: every frame of the explode opening and closing, its prefix states, and each accessory alone.
  const frames = [
    ...A.springStates(EXPLODE, { ...SPRING, stride: 2 }),
    ...A.prefixStates(EXPLODE, { shares: [0.5, 1] }),
    ...["handle", "stab", "brake", "gashatch"].map((id) => ({ label: `${id} out`, shares: { [id]: 1 } })),
  ];
  A.auditOrExit(R, P, { argv: ["--audit"], frames });
}
